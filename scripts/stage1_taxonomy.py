"""Stage 1.4: tag every train sample with the situation taxonomy and summarise.

Outputs: work/tags.jsonl ({id, structural, linguistic}), work/tags_review.csv (200 stratified rows to check by hand),
reports/stage1_taxonomy.md (aggregates). Run: python scripts/stage1_taxonomy.py
"""
from __future__ import annotations

import csv
import json
import random
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from lifemate.data import PROJECT, catalog_tools, load_samples  # noqa: E402
from lifemate.splits import label_type  # noqa: E402
from lifemate.taxonomy import LING, linguistic_tags, structural_tags  # noqa: E402

train = load_samples("train")
pub = load_samples("public_test")
kind = {n: t["kind"] for n, t in catalog_tools("train").items()}

rows = []
for s in train:
    rows.append({"id": s["id"], "structural": structural_tags(s, kind), "linguistic": linguistic_tags(s["audio_text"]),
                 "label_type": label_type(s["label"]["tool_calls"]), "n_calls": len(s["label"]["tool_calls"]),
                 "history_turns": len(s["history"])})
(PROJECT / "work").mkdir(exist_ok=True)
with open(PROJECT / "work" / "tags.jsonl", "w", encoding="utf-8") as f:
    for r in rows:
        f.write(json.dumps(r, ensure_ascii=False) + "\n")

# review sheet: up to 18 hits per linguistic tag + random rest, to estimate regex precision by hand
rng = random.Random(1)
by_id = {s["id"]: s for s in train}
pick = []
for tag in LING:
    hits = [r["id"] for r in rows if tag in r["linguistic"] and r["id"] not in pick]
    rng.shuffle(hits)
    pick += hits[:18]
rest = [r["id"] for r in rows if r["id"] not in pick]
rng.shuffle(rest)
pick += rest[:200 - len(pick)]
with open(PROJECT / "work" / "tags_review.csv", "w", encoding="utf-8-sig", newline="") as f:
    w = csv.writer(f)
    w.writerow(["id", "audio_text", "linguistic_tags", "structural_tags", "gold_calls", "correct_tags (fill)", "missing_tags (fill)"])
    tags = {r["id"]: r for r in rows}
    for sid in pick:
        s = by_id[sid]
        w.writerow([sid, s["audio_text"], " ".join(tags[sid]["linguistic"]), " ".join(tags[sid]["structural"]),
                    " ; ".join(c["name"] for c in s["label"]["tool_calls"]), "", ""])

n = len(rows)
st = Counter(t for r in rows for t in r["structural"])
li = Counter(t for r in rows for t in r["linguistic"])
md = ["# Stage 1.4 - situation taxonomy", "",
      "Generated by `scripts/stage1_taxonomy.py`. Structural tags come from the gold label (exact).",
      "Linguistic tags are regexes on the reference transcript (approximate; precision to be confirmed on `work/tags_review.csv`).", "",
      "## Structural tags (train)", "", "| tag | samples | share |", "|---|---|---|"]
md += [f"| {k} | {v} | {100 * v / n:.1f}% |" for k, v in st.most_common()]
md += ["", "## Linguistic tags (train transcripts)", "", "| tag | samples | share | label mix of tagged samples (action / read_then_ask / ask / empty) |", "|---|---|---|---|"]
for k, v in li.most_common():
    mix = Counter(r["label_type"] for r in rows if k in r["linguistic"])
    md.append(f"| {k} | {v} | {100 * v / n:.1f}% | {mix['action']} / {mix['read_then_ask']} / {mix['ask']} / {mix['empty']} |")

# how gold resolves the hard linguistic phenomena
md += ["", "## How the gold resolves hard phenomena", ""]
for tag in ("conditional", "self_repair", "negation"):
    sub = [r for r in rows if tag in r["linguistic"]]
    calls = Counter(r["n_calls"] for r in sub)
    ro = sum(1 for r in sub if "read_only" in r["structural"])
    em = sum(1 for r in sub if "empty" in r["structural"])
    md.append(f"- **{tag}** ({len(sub)}): gold empty {em}, read-only (condition checked, nothing done) {ro}, "
              f"with a write {sum(1 for r in sub if r['label_type'] == 'action') - ro}; calls per sample {dict(sorted(calls.items()))}.")
md += ["", "## Co-occurrence: number of tags per sample", ""]
k_tags = Counter(min(len(r["linguistic"]) + len([t for t in r["structural"] if t not in ('empty',)]), 6) for r in rows)
md.append(", ".join(f"{k}{'+' if k == 6 else ''} tags: {v}" for k, v in sorted(k_tags.items())))

pub_li = Counter()
md += ["", "## Same regexes on public_test", "",
       "public_test has no transcript; these tags will be computed on ASR output once Stage 1.2 picks an ASR."]
(PROJECT / "reports" / "stage1_taxonomy.md").write_text("\n".join(md) + "\n", encoding="utf-8")
print("\n".join(md))
