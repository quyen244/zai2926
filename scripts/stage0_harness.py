"""Stage 0: build the train gold (with replayed state hashes), the validation splits, and check the submission validator.

Outputs
  work/gold_train.jsonl      per-sample gold {id, tool_calls, state_hash}   (git-ignored: derived from the data)
  splits/cv5.json            {id: fold}                                      (ids only)
  splits/leave_app_out.json  {"held_out_apps", "train": [...], "val": [...]}
  reports/stage0.md          summary
Run from the project root:  python scripts/stage0_harness.py
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from lifemate.data import PROJECT, fuzzy_params, load_samples  # noqa: E402
from lifemate.gold import build_gold, initial_hash, validate_submission, write_submission  # noqa: E402
from lifemate.scoring import score_split  # noqa: E402
from lifemate.splits import HELD_OUT_APPS, cv_folds, label_type, leave_app_out  # noqa: E402

WORK, SPLITS, REPORTS = PROJECT / "work", PROJECT / "splits", PROJECT / "reports"


def main() -> None:
    for d in (WORK, SPLITS, REPORTS):
        d.mkdir(exist_ok=True)
    train = load_samples("train")
    fuzzy = fuzzy_params("train")

    gold = build_gold("train")
    write_submission([{"id": k, **v} for k, v in gold.items()], WORK / "gold_train.jsonl")
    bad_replay = [k for k, v in gold.items() if not v["replay_ok"]]
    self_score, _ = score_split(gold, gold, fuzzy)

    # floor: submit nothing - the anchor every later baseline must beat
    empty = {k: {"tool_calls": [], "state_hash": initial_hash("train", k)} for k in gold}
    empty_score, _ = score_split(empty, gold, fuzzy)

    folds = cv_folds(train)
    lao = leave_app_out(train)
    (SPLITS / "cv5.json").write_text(json.dumps(folds, indent=0, sort_keys=True), encoding="utf-8")
    (SPLITS / "leave_app_out.json").write_text(json.dumps({"held_out_apps": list(HELD_OUT_APPS), **lao}, indent=0), encoding="utf-8")

    by_id = {s["id"]: s for s in train}
    fold_mix = {f: Counter(label_type(by_id[i]["label"]["tool_calls"]) for i, ff in folds.items() if ff == f) for f in range(5)}
    lao_mix = {k: Counter(label_type(by_id[i]["label"]["tool_calls"]) for i in v) for k, v in lao.items()}

    # validator: an all-empty public_test submission must be valid; the shipped 3-line sample must be flagged as incomplete
    pub = load_samples("public_test")
    tmp = WORK / "empty_public_test.jsonl"
    write_submission([{"id": s["id"], "tool_calls": [], "state_hash": initial_hash("public_test", s["id"])} for s in pub], tmp)
    v_empty = validate_submission(tmp, "public_test")
    v_sample = validate_submission(PROJECT / "data/train+public_test/public_test/sample_submission.jsonl", "public_test")
    v_gold = validate_submission(WORK / "gold_train.jsonl", "train")

    kinds = ["action", "read_then_ask", "ask", "empty"]
    lines = [
        "# Stage 0 - scoring harness",
        "",
        "Generated by `scripts/stage0_harness.py`. Aggregates only; per-sample files stay in `work/` (git-ignored).",
        "",
        "## Gold and scorer",
        "",
        f"- Train samples: {len(gold)}. Gold replays that reproduce `final_state` and `tool_results` exactly: {len(gold) - len(bad_replay)}/{len(gold)}.",
        f"- Gold scored against itself: {self_score:.2f}.",
        f"- Floor, submit `[]` everywhere (initial-state hash): {empty_score:.2f}.",
        "- Unit tests: `python -m pytest tests` (scorer edge cases + the two checks above on real data).",
        "",
        "## Validation splits",
        "",
        "| fold | " + " | ".join(kinds) + " | total |",
        "|---|" + "---|" * (len(kinds) + 1),
    ]
    for f in range(5):
        lines.append(f"| {f} | " + " | ".join(str(fold_mix[f][k]) for k in kinds) + f" | {sum(fold_mix[f].values())} |")
    lines += [
        "",
        f"Leave-app-out held-out apps (train-only, absent from public_test): {', '.join(HELD_OUT_APPS)}.",
        "",
        "| part | " + " | ".join(kinds) + " | total |",
        "|---|" + "---|" * (len(kinds) + 1),
    ]
    for k in ("train", "val"):
        lines.append(f"| {k} | " + " | ".join(str(lao_mix[k][x]) for x in kinds) + f" | {len(lao[k])} |")
    lines += [
        "",
        "Samples whose gold uses no held-out app stay in `train`; empty-gold samples therefore never land in `val`,",
        "so leave-app-out measures app generalisation, and cv5 measures everything else.",
        "",
        "## Submission validator",
        "",
        f"- All-empty public_test submission ({len(pub)} lines): {'valid' if not v_empty else v_empty[:3]}.",
        f"- Gold train file: {'valid' if not v_gold else str(len(v_gold)) + ' problems, e.g. ' + str(v_gold[:2])}.",
        f"- Shipped `sample_submission.jsonl` (3 lines): flagged as expected: {v_sample[-1] if v_sample else 'NOT FLAGGED'}.",
        "",
    ]
    (REPORTS / "stage0.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
