"""Stage 1.3 / 1.5 / 1.6: anatomy of the labels, schema and environment behaviour, history.

Writes reports/stage1_labels.md (aggregates only, safe for the public repo) and work/stage1_examples.md (with transcripts).
Run: python scripts/stage1_labels.py
"""
from __future__ import annotations

import json
import re
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from lifemate.data import PROJECT, catalog_tools, load_catalog, load_samples  # noqa: E402
from lifemate.gold import replay  # noqa: E402
from lifemate.splits import label_type  # noqa: E402

train = load_samples("train")
pub = load_samples("public_test")
T_tr, T_pt = catalog_tools("train"), catalog_tools("public_test")
KIND = {n: t["kind"] for n, t in {**T_tr, **T_pt}.items()}
md: list[str] = []
ex: list[str] = []


def h(title: str) -> None:
    md.extend(["", f"## {title}", ""])


def table(header: list[str], rows: list[list]) -> None:
    md.append("| " + " | ".join(header) + " |")
    md.append("|" + "---|" * len(header))
    md.extend("| " + " | ".join(str(c) for c in r) + " |" for r in rows)


def pct(a: int, b: int) -> str:
    return f"{100 * a / b:.1f}%" if b else "-"


md += ["# Stage 1 - labels, schema, environment, history", "",
       "Generated by `scripts/stage1_labels.py` on the train split (1545 samples) and the public_test inputs.",
       "Aggregates only. Examples with transcripts are in `work/stage1_examples.md` (git-ignored)."]

# ---------------------------------------------------------------- 1.3 label anatomy
h("1.3 Label types")
types = Counter()
read_only = 0
for s in train:
    c = s["label"]["tool_calls"]
    t = label_type(c)
    if t == "action" and not s["label"]["final_state"]:
        t = "read_only_answer"
        read_only += 1
    types[t] += 1
table(["type", "samples", "share"], [[k, v, pct(v, len(train))] for k, v in types.most_common()])
md.append("")
md.append("`read_only_answer` = the gold only reads (weather, balance, prices...) and changes no app data, so the hash equals the initial one and only the call match matters.")

h("1.3 Read/write shape of the gold trajectories")
shape = Counter("".join({"read": "R", "write": "W", "meta": "?"}[KIND.get(c["name"], "write")] for c in s["label"]["tool_calls"]) or "-" for s in train)
table(["shape (R=read, W=write, ?=ask)", "samples"], [[k, v] for k, v in shape.most_common(14)])

h("1.3 Argument conventions of gold read calls")
md.append("How often each read tool is called with no argument at all versus with filters. Every extra filter that the gold does not use makes the call unmatched.")
md.append("")
argsets = defaultdict(Counter)
for s in train:
    for c in s["label"]["tool_calls"]:
        if KIND.get(c["name"]) == "read":
            argsets[c["name"]][tuple(sorted(c["arguments"]))] += 1
rows = []
for name, cnt in sorted(argsets.items(), key=lambda kv: -sum(kv[1].values()))[:20]:
    n = sum(cnt.values())
    rows.append([name, n, pct(cnt[()], n), ", ".join(f"{'{' + ','.join(k) + '}'}:{v}" for k, v in cnt.most_common(3) if k)])
table(["read tool", "calls", "with {}", "argument sets used (top)"], rows)

# provenance of id-like argument values of write calls
h("1.3 / 1.6 Where do the IDs in write calls come from?")
md.append("For each write-call argument that references app data (`x-ref` in the catalog), look for its value in: (a) results of earlier calls in the same gold trajectory, (b) the history (assistant tool results), (c) nowhere.")
md.append("")
prov = Counter()
prov_by_tool = defaultdict(Counter)
for s in train:
    hist_blob = json.dumps(s["history"], ensure_ascii=False)
    calls, results = s["label"]["tool_calls"], s["label"]["tool_results"]
    for i, c in enumerate(calls):
        if KIND.get(c["name"]) != "write":
            continue
        props = T_tr[c["name"]]["parameters"].get("properties", {})
        for k, v in c["arguments"].items():
            if "x-ref" not in props.get(k, {}):
                continue
            needle = json.dumps(v, ensure_ascii=False)
            if any(needle in json.dumps(r, ensure_ascii=False) for r in results[:i]):
                src = "earlier read in same turn"
            elif needle in hist_blob:
                src = "history only"
            else:
                src = "not found (known from context or guessed)"
            prov[src] += 1
            prov_by_tool[c["name"]][src] += 1
n = sum(prov.values())
table(["source of the ID", "arguments", "share"], [[k, v, pct(v, n)] for k, v in prov.most_common()])
md.append("")
md.append("Implication: when the ID is already in the history, the gold usually writes directly without reading again; a policy that always reads first loses precision on those samples.")
hist_direct = sum(1 for s in train if s["history"] and s["label"]["tool_calls"] and KIND.get(s["label"]["tool_calls"][0]["name"]) == "write")
md.append(f"Samples with history whose first gold call is a write: {hist_direct}.")

# date-time formats
h("1.3 Date-time argument format")
fmt = Counter()
for s in train:
    for c in s["label"]["tool_calls"]:
        props = T_tr[c["name"]]["parameters"].get("properties", {})
        for k, v in c["arguments"].items():
            f = props.get(k, {}).get("format")
            if f and isinstance(v, str):
                shape_ = re.sub(r"\d", "9", v)
                fmt[(f, shape_)] += 1
table(["format", "value shape", "count"], [[f, f"`{s}`", v] for (f, s), v in fmt.most_common(8)])

# contacts.search queries
h("1.3 `contacts.search` queries")
q_in_text = q_total = q_cap = 0
for s in train:
    for c in s["label"]["tool_calls"]:
        if c["name"] == "contacts.search" and c["arguments"].get("query"):
            q = c["arguments"]["query"]
            q_total += 1
            q_cap += q[:1].isupper()
            q_in_text += q.lower() in s["audio_text"].lower()
md.append(f"- Calls with a query: {q_total}; query starts with a capital: {pct(q_cap, q_total)}; query appears verbatim (case-insensitive) in the final transcript: {pct(q_in_text, q_total)}.")
md.append("- So the query is mostly the name as spoken, including kinship or role words (e.g. a role word followed by a name), which ASR must get exactly right.")

# ask_missing
h("1.3 `sys.ask_missing_info`")
ask_params = Counter()
ask_after = Counter()
for s in train:
    calls, results = s["label"]["tool_calls"], s["label"]["tool_results"]
    for i, c in enumerate(calls):
        if c["name"] != "sys.ask_missing_info":
            continue
        ask_params[(c["arguments"]["tool_name"].split(".")[0], ",".join(c["arguments"]["params"]))] += 1
        if i:
            prev = results[i - 1]
            lists = [v for v in prev.values() if isinstance(v, list)]
            n_items = len(lists[0]) if lists else None
            ask_after[f"{calls[i - 1]['name']} -> {('0 results' if n_items == 0 else '1 result' if n_items == 1 else '2+ results' if n_items else 'non-list result')}"] += 1
        else:
            ask_after["asked immediately"] += 1
table(["asked tool app", "missing params", "count"], [[a, f"`{p}`", v] for (a, p), v in ask_params.most_common(12)])
md.append("")
table(["what came right before the ask", "count"], [[k, v] for k, v in ask_after.most_common(10)])

# empty labels
h("1.3 Empty gold (`[]`)")
empty_kind = Counter()
repair = re.compile(r"à (thôi|không|mà thôi)|thôi khỏi|thôi không|khỏi đi|không cần|đừng|thôi bỏ", re.I)
for s in train:
    if s["label"]["tool_calls"]:
        continue
    t = s["audio_text"].lower()
    k = "cancel / negation marker in speech" if repair.search(t) else "no marker (likely no suitable app)"
    empty_kind[k] += 1
    if len([e for e in ex if e.startswith("- [empty")]) < 12:
        ex.append(f"- [empty/{k}] {s['audio_text']}  (apps: {', '.join(s['context']['installed_apps'])})")
table(["empty-gold subtype (heuristic)", "samples"], [[k, v] for k, v in empty_kind.most_common()])

# silent failures in gold results
h("1.5 Silent failures inside gold trajectories")
done_false = Counter()
for s in train:
    for c, r in zip(s["label"]["tool_calls"], s["label"]["tool_results"]):
        if isinstance(r, dict) and r.get("done") is False:
            done_false[c["name"]] += 1
md.append(f"Gold results with `done: false`: {sum(done_false.values())} ({', '.join(f'{k}:{v}' for k, v in done_false.most_common(6)) or 'none'}).")

# ---------------------------------------------------------------- 1.5 schema
h("1.5 Catalog: train vs public_test")
apps_tr = {a["id"]: a for a in load_catalog("train")["apps"]}
apps_pt = {a["id"]: a for a in load_catalog("public_test")["apps"]}
shared = sorted(set(apps_tr) & set(apps_pt))
md.append(f"- Apps: train {len(apps_tr)}, public {len(apps_pt)}, shared {len(shared)}, public-only {len(set(apps_pt) - set(apps_tr))}, train-only {len(set(apps_tr) - set(apps_pt))}.")
md.append(f"- Public-only apps: {', '.join(sorted(set(apps_pt) - set(apps_tr)))}.")
diff_tools = []
for name in sorted(set(T_tr) & set(T_pt)):
    if T_tr[name]["parameters"] != T_pt[name]["parameters"]:
        diff_tools.append(name)
only_tr_tools = sorted(n for n in set(T_tr) - set(T_pt) if n.split(".")[0] in shared)
only_pt_tools = sorted(n for n in set(T_pt) - set(T_tr) if n.split(".")[0] in shared)
md.append(f"- Shared tools whose parameter schema differs between the two catalogs: {len(diff_tools)} ({', '.join(diff_tools[:12]) or 'none'}).")
md.append(f"- Tools of shared apps present only in train: {', '.join(only_tr_tools) or 'none'}; only in public: {', '.join(only_pt_tools) or 'none'}.")
feat = Counter()
for name, t in T_pt.items():
    p = t["parameters"]
    for k, v in (p.get("properties") or {}).items():
        for key in ("x-ref", "enum", "format"):
            if key in v:
                feat[key] += 1
        if v.get("x-match") == "fuzzy":
            feat["x-match fuzzy"] += 1
    if p.get("x-one-of"):
        feat["tools with x-one-of"] += 1
md.append(f"- Public catalog parameter features: {', '.join(f'{k} {v}' for k, v in feat.most_common())}.")
inst_pt = Counter(len(s["context"]["installed_apps"]) for s in pub)
inst_tr = Counter(len(s["context"]["installed_apps"]) for s in train)
md.append(f"- Installed apps per sample: train median {statistics.median([len(s['context']['installed_apps']) for s in train])}, public median {statistics.median([len(s['context']['installed_apps']) for s in pub])}.")

h("1.5 Environment behaviour probes (train_0001..)")
md.append("Calls made on fresh envs to see what the agent observes on mistakes. Nothing here touches state.json directly.")
md.append("")
probe_rows = []
sid = train[0]["id"]
apps0 = train[0]["context"]["installed_apps"]
first_write = next((t for a in apps0.values() for t in a["tools"] if KIND.get(t) == "write"), None)
probes = [("unknown tool", "nope.tool", {}),
          ("tool of an app not installed", next(n for n in T_tr if n.split(".")[0] not in apps0 and n != "sys.ask_missing_info"), {}),
          ("missing required argument", first_write, {})]
if "smart_home.light_set" in {t for a in apps0.values() for t in a["tools"]}:
    probes += [("non-existent device id", "smart_home.light_set", {"device_id": "light_does_not_exist", "power": "off"}),
               ("wrong enum value", "smart_home.light_set", {"device_id": "x", "power": "maybe"})]
probes += [("ask_missing_info", "sys.ask_missing_info", {"tool_name": first_write, "params": ["x"]})]
for label, name, args in probes:
    _, res = replay("train", sid, [{"name": name, "arguments": args}])
    probe_rows.append([label, f"`{name}`", f"`{json.dumps(res[0], ensure_ascii=False)[:110]}`"])
# not-found id on any sample that has a write with an x-ref param
for s in train[:200]:
    c = next((c for c in s["label"]["tool_calls"] if KIND.get(c["name"]) == "write" and any("x-ref" in T_tr[c["name"]]["parameters"]["properties"].get(k, {}) for k in c["arguments"])), None)
    if c:
        k = next(k for k in c["arguments"] if "x-ref" in T_tr[c["name"]]["parameters"]["properties"].get(k, {}))
        bad = {**c["arguments"], k: "does_not_exist_01"}
        env, res = replay("train", s["id"], [{"name": c["name"], "arguments": bad}])
        from lifemate.gold import initial_hash
        unchanged = env.get_state_hash() == initial_hash("train", s["id"])
        probe_rows.append([f"non-existent `{k}` ({s['id']})", f"`{c['name']}`", f"`{json.dumps(res[0], ensure_ascii=False)[:110]}` state unchanged: {unchanged}"])
        break
table(["probe", "tool", "result"], probe_rows)

# ---------------------------------------------------------------- 1.6 history
h("1.6 History")
for name, data in (("train", train), ("public_test", pub)):
    turns = [len(s["history"]) for s in data]
    users = sum(1 for s in data for t in s["history"] if t["role"] == "user")
    md.append(f"- {name}: samples with history {pct(sum(1 for x in turns if x), len(data))}; median turns (when present) {statistics.median([x for x in turns if x])}; max {max(turns)}; earlier user turns to transcribe: {users}.")
pub_hist_text = sum(1 for s in pub for t in s["history"] if t["role"] == "user" and t.get("audio_text"))
md.append(f"- public_test user turns that ship a transcript: {pub_hist_text} (so every earlier user turn must go through ASR).")


def prompt_chars(s: dict, T: dict) -> tuple[int, int]:
    tools = [T[n] for a in s["context"]["installed_apps"].values() for n in a["tools"] if n in T]
    schema = json.dumps([{"name": t["name"], "description": t["description"], "parameters": t["parameters"]} for t in tools], ensure_ascii=False)
    hist = json.dumps(s["history"], ensure_ascii=False)
    return len(schema), len(hist)


for name, data, T in (("train", train, T_tr), ("public_test", pub, T_pt)):
    sc, hc = zip(*(prompt_chars(s, T) for s in data))
    md.append(f"- {name} prompt size (characters, raw JSON): schemas median {statistics.median(sc):.0f} / max {max(sc)}; history median {statistics.median(hc):.0f} / max {max(hc)}. Rough tokens = chars / 3.")

# examples for the team (not committed)
ex_head = ["# Stage 1 examples (contain transcripts - do not commit)", ""]
for t in ("ask", "read_then_ask"):
    for s in [s for s in train if label_type(s["label"]["tool_calls"]) == t][:6]:
        ex.append(f"- [{t}] {s['audio_text']} -> {json.dumps(s['label']['tool_calls'], ensure_ascii=False)[:300]}")
for s in [s for s in train if s["history"]][:5]:
    ex.append(f"- [history {len(s['history'])} turns] LAST: {s['audio_text']} -> {json.dumps(s['label']['tool_calls'], ensure_ascii=False)[:300]}")

(PROJECT / "reports").mkdir(exist_ok=True)
(PROJECT / "work").mkdir(exist_ok=True)
(PROJECT / "reports" / "stage1_labels.md").write_text("\n".join(md) + "\n", encoding="utf-8")
(PROJECT / "work" / "stage1_examples.md").write_text("\n".join(ex_head + ex) + "\n", encoding="utf-8")
print("\n".join(md))
