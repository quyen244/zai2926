"""Tool-selection rationales for the SFT trajectories, AutoTool style (arXiv 2512.13278: a rationale inside a select
block before every tool call, generated by an expert model from the question + toolset + solved trajectory and kept
only when it names the right tool). Train folds only (never CV fold 0, never public/private test).

Each gold trajectory is replayed on a fresh ToolEnv and every step is tagged by code:
  tra_cuu   a lookup whose result supplies an ID used by a later call
  kiem_tra  a lookup in a conditional request that supplies no ID
  dieu_kien the first write after a kiem_tra lookup
  nguon     a call with an ID taken from an earlier result
  co_san    a call with an ID already in the prompt / history
  tinh_ra   a call with a time / amount the user did not say verbatim and no earlier result holds (worked out)
  chuan_hoa a value not written exactly so in the (unnormalised) turn the agent sees: "8 giờ kém 15 tối", "sếp dũng"
gpt-oss writes, for every step, "select" (why this tool now) + "tool"; steps tagged nguon / co_san / dieu_kien also get
"args" (where the values the user did not say come from; targets EDA group 1c).

  python scripts/rationale_data.py --show train_0011     # the filled prompt for one sample, no call
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from eda_drill import COND, contains, is_write, norm, replay, value_type  # noqa: E402
from lifemate.data import PROJECT, load_samples  # noqa: E402
from lifemate.normalize import normalize_text  # noqa: E402
from lifemate.prompt import build_prompt  # noqa: E402
from lifemate.scoring import _args  # noqa: E402

PROMPTS = PROJECT / "prompts"
CV = json.loads((PROJECT / "splits" / "cv5.json").read_text(encoding="utf-8"))
MODEL = "openai/gpt-oss-120b"
ARGS_TAGS = {"nguon", "co_san", "dieu_kien", "tinh_ra", "chuan_hoa"}


def tag_steps(sample: dict) -> list[dict]:
    calls = sample["label"]["tool_calls"]
    seen = replay(sample, calls)
    ctx = norm(json.dumps(build_prompt(sample, "train", sample["audio_text"], None)["messages"], ensure_ascii=False))
    steps = [{"i": i, "call": c, "result": r, "tags": []} for i, (c, r) in enumerate(seen)]
    supplies = set()
    for j, st in enumerate(steps):
        for k, v in _args(st["call"]).items():
            is_id = value_type(k, v) == "id" and isinstance(v, str)
            # other values count only when the user did not say them: a phone, an amount read from a bill
            if not is_id and (isinstance(v, (bool, list, dict)) or len(str(v)) < 4 or contains(norm(sample["audio_text"]), v)):
                continue
            src = next((i for i in range(j) if contains(norm(steps[i]["result"]), v)), None)
            if src is not None:
                supplies.add(src)
                st["tags"].append(("nguon", k, v, src))
            elif is_id and contains(ctx, v):
                st["tags"].append(("co_san", k, v, None))
            elif not is_id:  # a time / amount the user did not say verbatim and no result holds: worked out
                st["tags"].append(("tinh_ra", k, v, None))
    cond = bool(COND.search(sample["audio_text"].lower()))
    checked = False
    for st in steps:
        name = st["call"]["name"]
        if name.startswith("sys."):
            continue
        if not is_write(name):
            if st["i"] in supplies:
                st["tags"].insert(0, ("tra_cuu",))
            elif cond:
                st["tags"].insert(0, ("kiem_tra",))
                checked = True
        elif checked:
            st["tags"].insert(0, ("dieu_kien",))
            checked = False
    return steps


def needs_args(st: dict) -> bool:
    """A call whose values are not all said by the user: an ID from a result or the prompt, or a value set by a condition."""
    return any(t[0] in ARGS_TAGS for t in st["tags"])


def view(sample: dict, v: str) -> tuple[str, str]:
    """(final user turn as the agent sees it, every message of the agent's prompt as JSON) for text variant v.
    Spoken words, not normalised (normalise=False): the model converts them itself in its args rationale."""
    if v == "gold":
        p = build_prompt(sample, "train", sample["audio_text"], None, normalise=False)
    else:
        p = build_prompt(sample, "train", asr_text()[sample["audio"]], asr_text(), normalise=False)
    return p["messages"][-1]["content"], json.dumps(p["messages"], ensure_ascii=False)


_ASR: dict = {}


def asr_text() -> dict:
    """{audio -> hyp} of the fine-tuned PhoWhisper (final and history turns), the text the Docker agent will see."""
    if not _ASR:
        for line in (PROJECT / "work/asr/phowhisper_ft/train.jsonl").read_text(encoding="utf-8").splitlines():
            if line.strip():
                r = json.loads(line)
                _ASR[r["audio"]] = r["hyp"]
    return _ASR


def vague_tags(sample: dict, steps: list[dict], v: str) -> None:
    """A value that is not written exactly so (case-sensitive) in the turn the agent sees must be converted by the
    model ("8 giờ kém 15 tối" -> 19:45, "sếp dũng" -> "Sếp Dũng", "ngân hàng" -> bank): that step gets an args line."""
    seen = view(sample, v)[0]
    for st in steps:
        if any(t[0] in ARGS_TAGS for t in st["tags"]):
            continue
        for k, val in _args(st["call"]).items():
            if isinstance(val, bool) or val in (None, "", [], {}):
                continue
            if json.dumps(val, ensure_ascii=False).strip('"') not in seen:
                st["tags"].append(("chuan_hoa", k, val, None))
                break


def same_as_gold(sample: dict) -> bool:
    """The agent sees the same final turn with ASR as with gold text: the gold rationale is reused, no call."""
    key = lambda t: re.sub(r"[^\w]+", " ", t.lower()).strip()  # noqa: E731
    return key(view(sample, "asr")[0]) == key(view(sample, "gold")[0])


def steps_for(sample: dict, v: str) -> list[dict]:
    steps = tag_steps(sample)
    vague_tags(sample, steps, v)
    return steps


def fill(sample: dict, steps: list[dict], v: str = "gold") -> tuple[str, str]:
    """AutoTool-style (arXiv 2512.13278, A.4): the question, the toolset, the solved steps -> per step a selection
    rationale + the tool, plus an args line where a value is not in the user's words. For v = "asr" the model also
    sees the true sentence but writes from the ASR text the agent sees (prompts/rationale.asr.md)."""
    system = (PROMPTS / "rationale.system.md").read_text(encoding="utf-8")
    if v == "asr":
        system += (PROMPTS / "rationale.asr.md").read_text(encoding="utf-8")
    tools = build_prompt(sample, "train", sample["audio_text"], None)["tools"]
    toolset = "\n".join(f"{t['function']['name']} | {t['function']['description']}" for t in tools)
    lines = []
    for st in steps:
        c = st["call"]
        lines.append(f"Bước {st['i'] + 1}: {c['name']} {json.dumps(_args(c), ensure_ascii=False)}\n  kết quả: {st['result']}")
    asks = ", ".join(f"Bước {st['i'] + 1}" for st in steps if needs_args(st)) or "không có bước nào"
    tmpl = "rationale.user.asr.md" if v == "asr" else "rationale.user.md"
    user = (PROMPTS / tmpl).read_text(encoding="utf-8").format(
        gold=sample["audio_text"], utterance=view(sample, v)[0],
        toolset=toolset, steps="\n".join(lines), asks=asks)
    return system, user


NUM = re.compile(r"\d{1,3}(?:[ .,  ]\d{3})+(?!\d)|\d[\d.,]*\d|\d")  # 210 000, 1.250.000, 2,800,000
ID = re.compile(r"\b[a-z0-9]+(?:_[a-z0-9]+)+\b")  # evt_01, light_living, light_bedroom2
OUT = {v: PROJECT / "work" / "sft" / f"rationale.{v}.jsonl" for v in ("gold", "asr")}  # per-sample cache: raw gpt-oss replies
QUOTE = re.compile(r'["“”‘’«»]([^"“”‘’«»]{2,60})["“”‘’«»]')  # words the rationale presents as the user's


def nums(text: str) -> set[str]:
    """Numbers with 2+ digits, thousand separators dropped (1.250.000 -> 1250000), leading zeros kept apart."""
    return {x for x in (re.sub(r"[ .,  ]", "", m) for m in NUM.findall(text)) if len(x) >= 2}


def check(sample: dict, steps: list[dict], content: str, v: str = "gold") -> list[dict]:
    """Per step: the model's select / tool / args and the reasons to reject it (empty = kept).
    Kept only when the tool is the gold one (AutoTool's filter, by code) and every ID / number in the text was
    already seen at that step: the user's words or history, an earlier result, or the step's own arguments."""
    m = re.search(r"\[.*\]", content, re.S)
    try:
        rows = {int(r["buoc"]): r for r in json.loads(m.group(0))} if m else {}
    except (ValueError, TypeError, KeyError):
        rows = {}
    ctx = view(sample, v)[1]  # what the agent sees: for asr, the ASR final + history turns, never the gold text
    tools = build_prompt(sample, "train", sample["audio_text"], None)["tools"]
    names = {t["function"]["name"] for t in tools}
    keys = {k for t in tools for k in (t["function"].get("parameters") or {}).get("properties", {})}  # chat_id, order_id
    short = {n.split(".")[-1] for n in names} | {n.split(".")[0] for n in names} | names | keys  # not IDs
    # a copied tool name: "app.func", or a func name with "_" (light_set); a bare "email" / "sms" is plain Vietnamese
    copied = names | {f for n in names for f in [n.split(".")[-1]] if "_" in f}
    ctx += sample["context"]["current_time"]  # "mai" = today + 1: the model may cite today's date
    out = []
    for st in steps:
        r, bad = rows.get(st["i"] + 1), []
        if r is None:
            out.append({"i": st["i"], "select": None, "tool": None, "args": None, "bad": ["không có trong output"]})
            continue
        sel, args = str(r.get("select") or ""), r.get("args")
        if r.get("tool") != st["call"]["name"]:
            bad.append(f"tool {r.get('tool')} khác gold")
        if not sel:
            bad.append("thiếu select")
        if needs_args(st) and not args:
            bad.append("thiếu args")
        seen = ctx + "".join(steps[j]["result"] for j in range(st["i"])) + json.dumps(_args(st["call"]), ensure_ascii=False)
        text = sel + " " + str(args or "")
        bad += [f"mã {x} chưa thấy" for x in sorted(set(ID.findall(text)) - short) if x not in seen]
        bad += [f"chép tên tool {x}" for x in sorted({n for n in copied if re.search(rf"(?<![\w.]){re.escape(n)}(?!\w)", sel)})]
        # the arithmetic of a conversion is allowed: "kém 15" -> 60 - 15, "tối" -> + 12 (numbers up to 60)
        # seen in spoken form counts too: "500 nghìn" in the sentence allows 500000 / 500.000 in the rationale
        bad += [f"số {x} chưa thấy" for x in sorted(nums(text) - nums(seen) - nums(normalize_text(seen)) - {"8601"}) if int(x) > 60]
        low = lambda t: " ".join(t.lower().split())  # noqa: E731  quotes are the spoken words, not normalised
        bad += [f'trích "{q}" chưa thấy' for q in QUOTE.findall(text) if not ID.fullmatch(q) and low(q) not in low(seen)]
        if len(text.split()) > 80:
            bad.append(f"dài {len(text.split())} từ")
        out.append({"i": st["i"], "select": sel, "tool": r.get("tool"), "args": args, "bad": bad})
    return out


def load(v: str) -> dict:
    f = OUT[v]
    return {json.loads(x)["id"]: json.loads(x) for x in f.read_text(encoding="utf-8").splitlines() if x.strip()} if f.is_file() else {}


def run(n: int, workers: int, v: str = "gold") -> None:
    from paraphrase import ask  # the Kaggle model proxy client (token refresh, retries)
    done = load(v)
    pool_s = [s for s in load_samples("train") if CV.get(s["id"]) not in (0, None) and s["label"]["tool_calls"]][:n]
    todo = [s for s in pool_s if s["id"] not in done]
    if v == "asr":  # the agent sees the same text as with gold: reuse the gold reply, no call
        gold = load("gold")
        same = [s for s in todo if s["id"] in gold and same_as_gold(s)]
        OUT[v].parent.mkdir(parents=True, exist_ok=True)
        with OUT[v].open("a", encoding="utf-8") as f:
            for s in same:
                done[s["id"]] = {**gold[s["id"]], "same_as_gold": True}
                f.write(json.dumps(done[s["id"]], ensure_ascii=False) + "\n")
        todo = [s for s in todo if s["id"] not in done]
        print(f"{len(same)} samples with the same text as gold reuse the gold reply", flush=True)
    print(f"{v}: {len(pool_s)} samples, {len(pool_s) - len(todo)} done, {len(todo)} to call", flush=True)

    def one(s: dict) -> dict:
        steps = steps_for(s, v)
        system, user = fill(s, steps, v)
        r = ask(MODEL, system, user, effort="medium")
        return {"id": s["id"], "model": MODEL, "content": r.get("content", ""), "error": r.get("error"),
                "usage": r.get("usage", {}), "sec": r.get("sec")}

    from concurrent.futures import ThreadPoolExecutor
    OUT[v].parent.mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(workers) as ex, OUT[v].open("a", encoding="utf-8") as f:
        for row in ex.map(one, todo):
            if not row["error"]:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
                f.flush()
            done[row["id"]] = row
            print(f"  {row['id']}  {row['sec']} s  {row['error'] or ''}", flush=True)
    report([s for s in pool_s if s["id"] in done], done, v)


def report(samples: list[dict], done: dict, v: str = "gold") -> None:
    n_step = n_ok = n_args = n_args_ok = 0
    reasons = {}
    for s in samples:
        steps = steps_for(s, v)
        res = check(s, steps, done[s["id"]].get("content", ""), v)
        print(f"\n== {s['id']}  (fold {CV.get(s['id'])})  {s['audio_text']}"
              + (f"\n   asr: {view(s, 'asr')[0]}" if v == "asr" else ""))
        for st, r in zip(steps, res):
            c = st["call"]
            mark = "ok" if not r["bad"] else "LOẠI: " + "; ".join(r["bad"])
            print(f"    <select> {r['select']}")
            if r["args"]:
                print(f"    <args>   {r['args']}")
            print(f"    -> {c['name']} {json.dumps(_args(c), ensure_ascii=False)}   [{mark}]")
            n_step += 1
            n_ok += not r["bad"]
            if needs_args(st):
                n_args += 1
                n_args_ok += not r["bad"]
            for b in r["bad"]:
                k = re.sub(r"\S*\d\S*", "#", b)
                reasons[k] = reasons.get(k, 0) + 1
    print(f"\nsteps kept {n_ok}/{n_step} ({100 * n_ok / max(1, n_step):.0f}%), args steps kept {n_args_ok}/{n_args}")
    for k, v in sorted(reasons.items(), key=lambda x: -x[1]):
        print(f"  {v:3d}  {k}")
    tok = [done[s["id"]].get("usage", {}) for s in samples]
    print(f"tokens in {sum(t.get('prompt_tokens', 0) for t in tok)}, out {sum(t.get('completion_tokens', 0) for t in tok)}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--show", help="sample id (train folds 1-4 only): print the filled prompt, no call")
    ap.add_argument("--run", type=int, help="call gpt-oss on the first N fold 1-4 samples with calls, check and print")
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--text", choices=["gold", "asr"], default="gold", help="asr: write from the fine-tuned PhoWhisper text")
    a = ap.parse_args()
    if a.run:
        return run(a.run, a.workers, a.text)
    if CV.get(a.show) == 0:
        raise SystemExit(f"{a.show} is in CV fold 0 (the eval fold): never used for training data")
    s = {x["id"]: x for x in load_samples("train")}[a.show]
    steps = steps_for(s, a.text)
    print(f"== {s['id']}  (fold {CV.get(s['id'])})  {s['audio_text']}")
    if a.text == "asr":
        print(f"   asr: {view(s, 'asr')[0]}   (same as gold: {same_as_gold(s)})")
    print()
    for st in steps:
        c = st["call"]
        tags = ", ".join(t[0] + (f" {t[1]}={t[2]} từ bước {t[3] + 1}" if t[0] == "nguon" else f" {t[1]}={t[2]}" if t[0] == "chuan_hoa" else "") for t in st["tags"]) or "-"
        print(f"  [{tags}]\n    -> {c['name']} {json.dumps(_args(c), ensure_ascii=False)}\n         = {st['result'][:220]}")
    system, user = fill(s, steps, a.text)
    print("\n== SYSTEM PROMPT ==\n" + system + "\n== USER PROMPT ==\n" + user)


if __name__ == "__main__":
    main()
