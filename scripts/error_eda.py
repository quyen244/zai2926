"""Error EDA of a cached Kaggle run: which tool-calling stage fails, how often (% of the run's samples).

  python scripts/error_eda.py                      # every cache file in work/kaggle/cache (B0 = gold text, B1 = asr text)
  python scripts/error_eda.py --examples 8         # ids listed per error group

Run it after every experiment: this table is the standard evaluation of a run (see .claude/CLAUDE.md).
No model runs: it reads the cached predictions and the train labels, scores with lifemate.scoring.
Writes reports/error_eda.md (aggregates only, the repo is public) and work/eda/error_examples.md (ids, calls, commands).
Group definitions: lifemate/eda.py. Ids per group: scripts/error_ids.py. One sample side by side: scripts/compare_sample.py.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from lifemate.data import PROJECT  # noqa: E402
from lifemate.eda import CACHE_DIR, GROUPS, LOOKUPS, load_runs  # noqa: E402

def short(calls: list[dict]) -> str:
    return "; ".join(f"{c['name']}({json.dumps(c['arguments'], ensure_ascii=False)})" for c in calls) or "[]"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache-dir", type=Path, default=CACHE_DIR)
    ap.add_argument("--examples", type=int, default=6)
    a = ap.parse_args()

    runs = load_runs(a.cache_dir)

    rep = ["# Error EDA of the cached Kaggle runs", "",
           "Generated by `scripts/error_eda.py` from `work/kaggle/cache/` (no model run). Aggregates only; sample ids and calls are in `work/eda/error_examples.md` (git-ignored).",
           "A sample can belong to several groups, so the counts do not add up to the number of samples.", ""]
    ex = ["# Error examples (per-sample, git-ignored)", ""]
    names = [v for v, _ in runs]
    rep += ["Cells are the share of the run's samples in that group.", "",
            "| Group | " + " | ".join(f"{v} (n={len(res)})" for (v, _), res in runs.items()) + " |", "|---|" + "---:|" * len(names)]
    for key, title in GROUPS:
        cells = []
        for (v, f), res in runs.items():
            n = [r for r in res if key in r["labels"]]
            cells.append(f"{100 * len(n) / len(res):.1f}%" + (f" (điểm TB {100 * sum(r['score'] for r in n) / len(n):.1f})" if key == "multi_step" and n else ""))
        rep.append(f"| {title} | " + " | ".join(cells) + " |")
    for (v, f), res in runs.items():
        skipped, conf = Counter(), Counter()
        for r in res:
            skipped.update(r.get("skipped", []))
            conf.update(r.get("confusions", []))
        rep += ["", f"## {v}: {f.name}", "",
                f"Score {100 * sum(r['score'] for r in res) / len(res):.2f} / 100 on {len(res)} samples; full score {sum(r['score'] >= 0.999 for r in res)}, zero {sum(r['score'] == 0 for r in res)}.",
                "Lookup tools skipped (samples): " + ", ".join(f"`{t}` {skipped[t]}" for t in LOOKUPS) + ".",
                "Same-app confusions (predicted instead of gold): " + (", ".join(f"`{k}` {n}" for k, n in conf.most_common(8)) or "none") + "."]
        ex += [f"## {v}: {f.name}", ""]
        for key, title in GROUPS:
            hit = [r for r in res if key in r["labels"]]
            if not hit:
                continue
            ex += [f"### {title} ({len(hit)})", ""]
            for r in hit[: a.examples]:
                tf = "gold" if ".gold." in f.name else "asr"
                ex += [f"- **{r['id']}** điểm {r['score']:.2f} | {r['text']}", f"  - model: {short(r['pred'])}", f"  - gold:  {short(r['gold'])}",
                       f"  - trace: `.venv\\Scripts\\python.exe -X utf8 scripts\\trace_sample.py --id {r['id']} --text {tf} --llm cache`",
                       f"  - so sánh: `.venv\\Scripts\\python.exe -X utf8 scripts\\compare_sample.py {r['id']} --text {tf}`"]
            ex.append("")
    rep += ["", "## Reading", "",
            "Groups 1-6 follow the user's error taxonomy; 7 is reported with its mean score because a multi-step sample fails through the other groups.",
            "`wrong_tool` needs both an unrequested tool and a missing gold tool, so a pure extra call is only `over`.",
            "1a/1b/1c split `wrong_args` by the closest call of that tool: an extra argument, a missing argument, a gold argument with another value; a sample can have several.",
            "1a is what the open scoring question in TODO.md decides (strict vs relaxed)."]
    (PROJECT / "reports" / "error_eda.md").write_text("\n".join(rep) + "\n", encoding="utf-8")
    out = PROJECT / "work" / "eda" / "error_examples.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(ex) + "\n", encoding="utf-8")
    print("\n".join(rep))
    print(f"\n-> reports/error_eda.md, {out}")


if __name__ == "__main__":
    main()
