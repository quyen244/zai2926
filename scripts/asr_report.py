"""Stage 1.2: score the ASR bench outputs (work/asr/<model>.jsonl) against the train transcripts.

Metrics per model, overall and per taxonomy slice:
  - WER / CER on normalised text (lower, NFC, punctuation removed, simple number words -> digits);
  - gold-arg recall: of the gold tool-call string values that occur verbatim in the reference transcript
    (names, places, queries...), the share that also occurs in the hypothesis. This is the ASR error that reaches
    a non-fuzzy argument, hence the hash or the call match;
  - name recall: capitalised multi-word spans inside the reference (people, places);
  - hallucination rate: hypothesis with WER >= 0.8 or a known Whisper filler phrase;
  - real-time factor (decode seconds / audio seconds) on this machine's GPU.
Writes reports/stage1_asr.md (aggregates) and work/asr/worst_<model>.md (worst clips, with text).
Run: .venv\\Scripts\\python scripts/asr_report.py
"""
from __future__ import annotations

import json
import re
import statistics
import sys
import unicodedata
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import jiwer  # noqa: E402

from lifemate.data import PROJECT, load_samples  # noqa: E402

ASR = PROJECT / "work" / "asr"
NUM = {"không": "0", "một": "1", "hai": "2", "ba": "3", "bốn": "4", "năm": "5", "sáu": "6", "bảy": "7", "tám": "8", "chín": "9", "mười": "10"}
HALLU = re.compile(r"subscribe|đăng ký kênh|ghiền mì gõ|cảm ơn các bạn đã (theo dõi|xem)|hẹn gặp lại các bạn|like và share", re.I)
SLICES = ["dialect_central", "dialect_south", "money", "self_repair", "conditional", "english_word", "filler", "negation"]


def norm(s: str) -> str:
    s = unicodedata.normalize("NFC", s.lower())
    s = re.sub(r"[^\w\s]", " ", s)
    return " ".join(NUM.get(w, w) for w in s.split())


def contains(hay: str, needle: str) -> bool:
    return f" {norm(needle)} " in f" {norm(hay)} "


def names(ref: str) -> list[str]:
    spans = re.findall(r"(?<![.!?]\s)(?<!^)\b([A-ZĐÀ-Ỹ][\wÀ-ỹ]*(?:\s+[A-ZĐÀ-Ỹ][\wÀ-ỹ]*)+)", ref)
    return [s for s in spans if len(s) > 3]


def gold_strings(sample: dict) -> list[str]:
    vals = []
    for c in sample["label"]["tool_calls"]:
        for v in c["arguments"].values():
            if isinstance(v, str) and len(v) >= 2 and not re.fullmatch(r"[a-z0-9_\-:+T.]+", v) and contains(sample["audio_text"], v):
                vals.append(v)
    return vals


def main() -> None:
    train = {s["id"]: s for s in load_samples("train")}
    tags = {json.loads(line)["id"]: json.loads(line) for line in (PROJECT / "work" / "tags.jsonl").read_text(encoding="utf-8").splitlines()}
    results = {}
    for f in sorted(ASR.glob("*.jsonl")):
        rows = [json.loads(line) for line in f.read_text(encoding="utf-8").splitlines() if line.strip()]
        if not rows:
            continue
        per = []
        for r in rows:
            s = train[r["id"]]
            ref, hyp = norm(s["audio_text"]), norm(r["hyp"])
            wer = jiwer.wer(ref, hyp) if hyp else 1.0
            cer = jiwer.cer(ref, hyp) if hyp else 1.0
            gs = gold_strings(s)
            ns = names(s["audio_text"])
            per.append({"id": r["id"], "wer": wer, "cer": cer, "ref_words": len(ref.split()),
                        "ref_edits": wer * len(ref.split()),
                        "gold_hit": sum(contains(r["hyp"], g) for g in gs), "gold_n": len(gs),
                        "name_hit": sum(contains(r["hyp"], n) for n in ns), "name_n": len(ns),
                        "hallu": bool(HALLU.search(r["hyp"])) or wer >= 0.8,
                        "rtf": r["sec_decode"] / max(r["sec_audio"], 0.1), "sec": r["sec_audio"],
                        "hyp": r["hyp"], "ref": s["audio_text"]})
        results[f.stem] = per

    def agg(rows: list[dict]) -> dict:
        n_words = sum(r["ref_words"] for r in rows)
        g_n = sum(r["gold_n"] for r in rows)
        n_n = sum(r["name_n"] for r in rows)
        return {"n": len(rows),
                "wer": sum(r["ref_edits"] for r in rows) / n_words if n_words else 0,
                "cer": statistics.mean(r["cer"] for r in rows),
                "gold": sum(r["gold_hit"] for r in rows) / g_n if g_n else float("nan"),
                "name": sum(r["name_hit"] for r in rows) / n_n if n_n else float("nan"),
                "hallu": sum(r["hallu"] for r in rows) / len(rows),
                "perfect_gold": sum(1 for r in rows if r["gold_n"] and r["gold_hit"] == r["gold_n"]) / max(1, sum(1 for r in rows if r["gold_n"])),
                "rtf": statistics.median(r["rtf"] for r in rows)}

    md = ["# Stage 1.2 - ASR benchmark", "",
          "Generated by `scripts/asr_report.py` on the stratified train bench set (final user turn only).",
          "faster-whisper (CTranslate2, int8_float16, beam 5, language vi, no previous-text conditioning) on a GTX 1660 Ti 6 GB.",
          "Text normalised (lower, NFC, no punctuation, number words 0-10 -> digits) before WER/CER.", "",
          "| model | clips | WER | CER (mean) | gold-arg recall | samples with all gold strings | name recall | hallucination | RTF (median) |",
          "|---|---|---|---|---|---|---|---|---|"]
    for m, rows in results.items():
        a = agg(rows)
        md.append(f"| {m} | {a['n']} | {a['wer']:.3f} | {a['cer']:.3f} | {a['gold']:.3f} | {a['perfect_gold']:.3f} | {a['name']:.3f} | {a['hallu']:.3f} | {a['rtf']:.2f} |")
    md += ["", "## WER by slice", "", "| model | " + " | ".join(SLICES) + " | short (<5s) | long (>=9s) |", "|---|" + "---|" * (len(SLICES) + 2)]
    for m, rows in results.items():
        cells = []
        for t in SLICES:
            sub = [r for r in rows if t in tags[r["id"]]["linguistic"]]
            cells.append(f"{agg(sub)['wer']:.3f} ({len(sub)})" if sub else "-")
        for sub in ([r for r in rows if r["sec"] < 5], [r for r in rows if r["sec"] >= 9]):
            cells.append(f"{agg(sub)['wer']:.3f} ({len(sub)})" if sub else "-")
        md.append(f"| {m} | " + " | ".join(cells) + " |")
    md += ["", "## Gold-arg recall by slice", "", "| model | " + " | ".join(SLICES) + " |", "|---|" + "---|" * len(SLICES)]
    for m, rows in results.items():
        cells = []
        for t in SLICES:
            sub = [r for r in rows if t in tags[r["id"]]["linguistic"]]
            a = agg(sub) if sub else None
            cells.append(f"{a['gold']:.3f}" if a and a["gold"] == a["gold"] else "-")
        md.append(f"| {m} | " + " | ".join(cells) + " |")
    (PROJECT / "reports").mkdir(exist_ok=True)
    (PROJECT / "reports" / "stage1_asr.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    for m, rows in results.items():
        worst = sorted(rows, key=lambda r: -r["wer"])[:40]
        lines = [f"# Worst clips for {m} (contains transcripts - do not commit)", ""]
        lines += [f"- {r['id']} WER {r['wer']:.2f}\n  - REF: {r['ref']}\n  - HYP: {r['hyp']}" for r in worst]
        (ASR / f"worst_{m}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
