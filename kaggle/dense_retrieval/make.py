"""Build kaggle/dense_retrieval/run.py: the Kaggle kernel is one file, so the two retrieval scripts are embedded in it.

  python kaggle/dense_retrieval/make.py     # after any change to scripts/retrieval_dense.py or scripts/retrieval_recall.py

The dataset `lifemate-data` (code a209ba03 + train data + cached ASR) has no scripts/ folder, so run.py writes them into
the unpacked repo and runs scripts/retrieval_dense.py on both T4s (one bge-m3 copy per GPU, texts split in two shards).
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
TEMPLATE = '''"""Kaggle job: BGE-M3 vs BM25 tool retrieval recall on all train samples (GENERATED by make.py, do not edit by hand).

Flow: unpack the private dataset lifemate-data -> write the embedded scripts into repo/scripts -> run
scripts/retrieval_dense.py (bge-m3 downloaded from Hugging Face, one copy per GPU, texts sharded over both T4s) ->
/kaggle/working/{retrieval_dense.md, bge-m3.dense.npz, run.log}.
"""
import shutil
import subprocess
import sys
import tarfile
from pathlib import Path

WORK = Path("/kaggle/working")
REPO = WORK / "repo"
SCRIPTS = __SCRIPTS__

src = next((p for p in Path("/kaggle/input").rglob("repo.tar.gz")), None)
if src:
    with tarfile.open(src) as tar:
        tar.extractall(REPO)
else:  # Kaggle may have unpacked the archive itself
    d = next(p.parent.parent for p in Path("/kaggle/input").rglob("lifemate/agent.py"))
    shutil.copytree(d, REPO, dirs_exist_ok=True)
(REPO / "scripts").mkdir(exist_ok=True)
for name, code in SCRIPTS.items():
    (REPO / "scripts" / name).write_text(code, encoding="utf-8")
subprocess.run(["nvidia-smi", "--query-gpu=index,name,memory.total", "--format=csv"], check=False)
r = subprocess.run([sys.executable, "-X", "utf8", "scripts/retrieval_dense.py", "--batch", "32"], cwd=REPO)
for f in (REPO / "reports" / "retrieval_dense.md", REPO / "work" / "retrieval" / "bge-m3.dense.npz"):
    if f.is_file():
        shutil.copy(f, WORK / f.name)
shutil.rmtree(REPO, ignore_errors=True)
sys.exit(r.returncode)
'''


def main() -> None:
    scripts = {n: (ROOT / "scripts" / n).read_text(encoding="utf-8") for n in ("retrieval_dense.py", "retrieval_recall.py")}
    (HERE / "run.py").write_text(TEMPLATE.replace("__SCRIPTS__", repr(scripts)), encoding="utf-8")
    print(f"-> {HERE / 'run.py'}")


if __name__ == "__main__":
    main()
